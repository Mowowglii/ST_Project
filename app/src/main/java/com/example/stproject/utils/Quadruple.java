package com.example.stproject.utils;

public class Quadruple<T, U, V, W>{
    public final T first;
    public final U second;
    public final V third;
    public final W fourth;

    public Quadruple(T first, U second, V third, W fourth){
        this.first = first;
        this.second = second;
        this.third = third;
        this.fourth = fourth;
    }
}
